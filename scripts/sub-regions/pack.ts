// The packed form of the sub-region table, written to src/constants/sub-regions.data.ts and read back by
// src/constants/sub-regions.ts. One row to a line, fields split by "|" and aliases by "~", in the generator's order:
//   name|parentCity|state|type|alias~alias
// None of the characters occurs in a name, a city or an alias (the generator refuses a row that has one), so no
// escaping is needed. The alias field is left off a row that has none.
import type { SubRegion } from "../../src/types";

const FIELD = "|";
const ALIAS = "~";
const ROW = "\n";

// Characters that are structure to the decoder, or would end the template literal the text is written in.
const FORBIDDEN = /[|~\n`\\$]/;

// A row refuses them, since a decoder would read the separators as structure.
const checkField = (text: string, row: SubRegion): string => {
  if (FORBIDDEN.test(text)) {
    throw new Error(`Sub-region ${JSON.stringify(row)} holds a separator or a template-literal character`);
  }

  return text;
};

/** One sub-region as a row of the packed text. */
const packSubRegion = (row: SubRegion): string => {
  const fields = [row.name, row.parentCity, row.state, row.type].map((field) => checkField(field, row));
  if (row.aliases && row.aliases.length > 0)
    fields.push(row.aliases.map((alias) => checkField(alias, row)).join(ALIAS));

  return fields.join(FIELD);
};

/** The packed text of the rows of one country, in the order given. */
const packSubRegions = (rows: readonly SubRegion[]): string => rows.map(packSubRegion).join(ROW);

/** The whole source of src/constants/sub-regions.data.ts for rows already sorted (Canada first, then the United States). */
const renderSubRegionsData = (rows: readonly SubRegion[], generatedOn: string): string => {
  const canada = rows.filter((row) => row.country === "CA");
  const states = rows.filter((row) => row.country === "US");
  const byType = new Map<string, number>();
  for (const row of rows) byType.set(row.type, (byType.get(row.type) ?? 0) + 1);
  const typeStats = [...byType].map(([type, count]) => `${type}: ${count}`).join(", ");

  return `// Generated by scripts/sub-regions/update-sub-regions.ts on ${generatedOn}. Do not edit by hand.
// The boroughs, parishes, districts, wards and arrondissements of US and Canadian addresses, packed one row to a line
// as name|parentCity|state|type|alias~alias (scripts/sub-regions/pack.ts writes it, src/constants/sub-regions.ts reads it).
//
// - Total sub-regions: ${rows.length}
// - US sub-regions: ${states.length}
// - Canadian sub-regions: ${canada.length}
// - By type: ${typeStats}

const CA_SUB_REGIONS_PACKED = \`${ROW}${packSubRegions(canada)}\`;

const US_SUB_REGIONS_PACKED = \`${ROW}${packSubRegions(states)}\`;

export { CA_SUB_REGIONS_PACKED, US_SUB_REGIONS_PACKED };
`;
};

export { packSubRegion, packSubRegions, renderSubRegionsData };
